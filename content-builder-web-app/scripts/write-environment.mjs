import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const token = process.env.DEEPSEEK_TOKEN ?? '';
const tokenFilePath = path.join(__dirname, '../src/environments/deepseek-token.ts');

const content = `// Generated by scripts/write-environment.mjs — do not edit manually
export const deepseekToken = ${JSON.stringify(token)};
`;

fs.writeFileSync(tokenFilePath, content);
console.log(`deepseek-token.ts updated (token ${token ? 'set' : 'empty'})`);
